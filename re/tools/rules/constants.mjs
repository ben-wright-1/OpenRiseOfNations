const POST = {
  mul48: (v) => Math.imul(v, 48),
  mul10: (v) => Math.imul(v, 10),
  marine: (v) => X.i32(v - X.cdiv(v, 15) + 2),
};

function parseField(C, f) {
  const el = f.xml ? X.child(C, f.xml) : null; // a missing element behaves like an empty one (get_element creates it)
  const out = [];
  switch (f.parse) {
    case "item": out.push(X.getAttribNum(el, "value", -1)); break;
    case "fraction": out.push(X.fraction(X.getAttrib(el, "value", ""), f.mul)); break;
    case "entry_int": case "entry_fraction":
      for (let i = 0; i < f.count; i++) {
        const s = X.getAttrib(el, "entry" + i, "");
        out.push(f.parse === "entry_int" ? (s.length ? X.convertInt(s) : 0) : X.fraction(s, f.mul));
      }
      break;
    case "none": for (let i = 0; i < f.count; i++) out.push(f.def); break;
    default: throw new Error("bad parse " + f.parse);
  }
  return f.post ? out.map(POST[f.post]) : out;
}

// Returns { array: Int32Array(848) in struct-offset order, byName: {field: int | int[]} }.
export function loadConstants(dataDir) {
  const root = X.readXml(dataDir, "rules.xml");
  const C = X.child(root, "CONSTANTS");
  const array = new Int32Array(CONSTANTS_INTS);
  const byName = {};
  for (const f of CONSTANT_FIELDS) {
    const v = parseField(C, f);
    array.set(v, f.offset / 4);
    byName[f.name] = f.count === 1 && f.parse !== "entry_int" && f.parse !== "entry_fraction" ? v[0] : v;
  }
  return { array, byName };
}
