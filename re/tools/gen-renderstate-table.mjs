// Generates engine/render/renderstate_table.inc from re/iface/renderstates.json.
// Usage: node re/tools/gen-renderstate-table.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const j = JSON.parse(fs.readFileSync(path.join(root, 're/iface/renderstates.json'), 'utf8'));

const camel = (s) => s.toLowerCase().split('_').map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const opName = {
	DISABLE: 'Disable', SELECTARG1: 'SelectArg1', SELECTARG2: 'SelectArg2', MODULATE: 'Modulate', MODULATE2X: 'Modulate2x',
	MODULATE4X: 'Modulate4x', ADD: 'Add', ADDSIGNED: 'AddSigned', ADDSIGNED2X: 'AddSigned2x', SUBTRACT: 'Subtract',
	ADDSMOOTH: 'AddSmooth', BLENDDIFFUSEALPHA: 'BlendDiffuseAlpha', BLENDTEXTUREALPHA: 'BlendTextureAlpha',
	BLENDFACTORALPHA: 'BlendFactorAlpha', BLENDTEXTUREALPHAPM: 'BlendTextureAlphaPM', BLENDCURRENTALPHA: 'BlendCurrentAlpha',
};
const argName = { CURRENT: 'Current', DIFFUSE: 'Diffuse', SELECTMASK: 'SelectMask', SPECULAR: 'Specular', TEMP: 'Temp', TEXTURE: 'Texture', TFACTOR: 'TFactor' };
const addr = { WRAP: 'Wrap', MIRROR: 'Mirror', CLAMP: 'Clamp', BORDER: 'Border', MIRRORONCE: 'MirrorOnce' };
const blend = {
	NONE: 'None', ZERO: 'Zero', ONE: 'One', SRCCOLOR: 'SrcColor', INVSRCCOLOR: 'InvSrcColor', SRCALPHA: 'SrcAlpha',
	INVSRCALPHA: 'InvSrcAlpha', DESTALPHA: 'DestAlpha', INVDESTALPHA: 'InvDestAlpha', DESTCOLOR: 'DestColor',
	INVDESTCOLOR: 'InvDestColor', SRCALPHASAT: 'SrcAlphaSat',
};
const cmp = { NEVER: 'Never', LESS: 'Less', EQUAL: 'Equal', LESSEQUAL: 'LessEqual', GREATER: 'Greater', NOTEQUAL: 'NotEqual', GREATEREQUAL: 'GreaterEqual', ALWAYS: 'Always' };
const need = (table, k) => {
	if (!(k in table)) throw new Error(`unmapped value ${k}`);
	return table[k];
};

const stage = (s) =>
	`{O::${need(opName, s.colorop)}, A::${need(argName, s.colorarg1)}, A::${need(argName, s.colorarg2)}, ` +
	`O::${need(opName, s.alphaop)}, A::${need(argName, s.alphaarg1)}, A::${need(argName, s.alphaarg2)}, ` +
	`${s.texcoord}, X::${need(addr, s.address_u)}, X::${need(addr, s.address_v)}}`;

const lines = ['// Generated by re/tools/gen-renderstate-table.mjs from re/iface/renderstates.json. Do not edit.'];
for (const s of j.states) {
	if (s.index !== lines.length - 1) throw new Error(`states out of order at ${s.name}`);
	lines.push(
		`{"${s.name}", ${s.enables.raw}, B::${need(blend, s.blend.src)}, B::${need(blend, s.blend.dst)}, ` +
			`C::${need(cmp, s.alphaTest.func)}, ${s.alphaTest.ref}, C::${need(cmp, s.depth.func)}, ${s.depth.bias}, ` +
			`CullMode::${camel(s.cull) === 'Cw' ? 'CW' : camel(s.cull) === 'Ccw' ? 'CCW' : 'None'}, FillMode::${camel(s.fill)}, ${s.tfactor}u, ` +
			`{${stage(s.stages[0])}, ${stage(s.stages[1])}}},`,
	);
}
fs.writeFileSync(path.join(root, 'engine/render/renderstate_table.inc'), lines.join('\n') + '\n');
console.log(`wrote ${j.states.length} states`);
